#!/usr/bin/env python3
"""固定したUnicode公式データから、URLホスト比較に使う変換・NFC表を生成する。"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent


def source(directory, name):
    """保存済み原本のSHA-256を確認し、ネットワーク通信なしで読み込む。"""
    pins = json.loads((ROOT / 'third_party/unicode-urlhost/SOURCES.json').read_text())
    raw = (directory / name).read_bytes()
    if hashlib.sha256(raw).hexdigest() != pins[name]['sha256']:
        raise ValueError('Unicode source hash mismatch: ' + name)
    return raw.decode('utf-8')


def go_string(points):
    """コードポイント列をGoでも有効な文字列リテラルへ変換する。"""
    return json.dumps(''.join(chr(int(x, 16)) for x in points.split()), ensure_ascii=False)


def generate(directory):
    """UTS #46の区間表と、正準分解・結合・結合クラスを出力する。"""
    lines = ['// Code generated by scripts/generate-urlhost-tables.py; DO NOT EDIT.',
             '// Unicode 17.0.0公式表。出典とライセンスはthird_party/unicode-urlhostを参照。',
             'package urlhost', 'var idnaRanges = [...]idnaRange{']
    actions = {'valid': 0, 'deviation': 0, 'mapped': 1, 'ignored': 2,
               'disallowed': 3, 'disallowed_STD3_valid': 0, 'disallowed_STD3_mapped': 1}
    for line in source(directory, 'IdnaMappingTable.txt').splitlines():
        fields = line.split('#')[0].strip().split(';')
        if not fields[0]:
            continue
        end = int(fields[0].strip().split('..')[-1], 16)
        action = actions[fields[1].strip()]
        mapped = go_string(fields[2].strip()) if action == 1 else '""'
        lines.append(f'{{0x{end:X}, {action}, {mapped}}},')
    lines.append('}')
    records = {}
    for line in source(directory, 'UnicodeData.txt').splitlines():
        fields = line.split(';')
        records[int(fields[0], 16)] = (int(fields[3]), fields[5])
    excluded = set()
    for line in source(directory, 'CompositionExclusions.txt').splitlines():
        code = line.split('#')[0].strip()
        if code:
            excluded.add(int(code, 16))
    lines.append('var canonicalClasses = map[rune]uint8{')
    for code, (combining, _) in sorted(records.items()):
        if combining:
            lines.append(f'0x{code:X}: {combining},')
    lines.append('}')
    lines.append('var canonicalDecompositions = map[rune]string{')
    compositions = []
    for code, (combining, decomposition) in sorted(records.items()):
        if not decomposition or decomposition.startswith('<'):
            continue
        lines.append(f'0x{code:X}: {go_string(decomposition)},')
        parts = [int(x, 16) for x in decomposition.split()]
        if len(parts) == 2 and code not in excluded and records[parts[0]][0] == 0:
            compositions.append((parts[0] << 21 | parts[1], code))
    lines.append('}')
    lines.append('var canonicalCompositions = map[uint64]rune{')
    for key, code in sorted(compositions):
        lines.append(f'0x{key:X}: 0x{code:X},')
    lines.append('}')
    return subprocess.check_output(['gofmt'], input=('\n'.join(lines) + '\n').encode())


def main():
    """指定した公式データから生成し、--checkでは既存の生成物と照合する。"""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('sources', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate(args.sources)
    target = ROOT / 'internal/urlhost/tables_generated.go'
    if args.check:
        if target.read_bytes() != generated:
            raise SystemExit('URL host tables differ from pinned Unicode sources')
    else:
        target.write_bytes(generated)


if __name__ == '__main__':
    main()
