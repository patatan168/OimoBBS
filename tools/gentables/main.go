// Command gentables は固定済みWHATWG表をオフラインでGo配列へ変換する。
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run() error {
	b, err := os.ReadFile("third_party/whatwg/index-jis0208.txt")
	if err != nil {
		return err
	}
	if fmt.Sprintf("%x", sha256.Sum256(b)) != "341dcde7e8b984e9c7bbf5ed75c8da7c6087d47083a1a2b3ed558bfd5bef9468" {
		return fmt.Errorf("source hash mismatch")
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by tools/gentables; DO NOT EDIT.\n// WHATWG JIS0208固定表。出典とライセンスはthird_party/whatwgを参照。\npackage textcodec\nvar jis0208 = [...]rune{")
	scanner := bufio.NewScanner(bytes.NewReader(b))
	seen := map[int]bool{}
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Fields(line)
		if len(f) < 2 {
			return fmt.Errorf("bad table row")
		}
		p, e := strconv.Atoi(f[0])
		if e != nil || p < 0 || p > 11279 || seen[p] {
			return fmt.Errorf("invalid pointer")
		}
		r, e := strconv.ParseUint(f[1], 0, 32)
		if e != nil || r == 0 || r > 0x10ffff || r >= 0xd800 && r <= 0xdfff {
			return fmt.Errorf("invalid scalar")
		}
		seen[p] = true
		fmt.Fprintf(&out, "%d: 0x%X,\n", p, r)
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	fmt.Fprintln(&out, "}")
	code, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("internal/textcodec/table_generated.go", code, 0644)
}
